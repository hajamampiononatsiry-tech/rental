export const ThemeProvider = ({ children }) => {
  const [isDarkMode, setIsDarkMode] = useState(true);
  const [language, setLanguage] = useState('Français');

  useEffect(() => {
    const loadSettings = async () => {
      try {
        const savedTheme = await AsyncStorage.getItem('user_theme');
        const savedLang = await AsyncStorage.getItem('user_language');
        if (savedTheme !== null) setIsDarkMode(savedTheme === 'dark');
        if (savedLang !== null) setLanguage(savedLang);
      } catch (e) {
        console.log('Erreur chargement préférences', e);
      }
    };
    loadSettings();
  }, []);

  const toggleTheme = async (value) => {
    setIsDarkMode(value);
    await AsyncStorage.setItem('user_theme', value ? 'dark' : 'light');
  };

  const changeLanguage = async (lang) => {
    setLanguage(lang);
    await AsyncStorage.setItem('user_language', lang);
  };

  const theme = isDarkMode ? themes.dark : themes.light;
  const t = translations[language] || translations['Français'];

  return (
    <ThemeContext.Provider value={{ isDarkMode, toggleTheme, language, changeLanguage, theme, t }}>
      {children}
    </ThemeContext.Provider>
  );
};